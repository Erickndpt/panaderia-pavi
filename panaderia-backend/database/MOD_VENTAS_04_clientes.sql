-- Ejecutar como SYSTEM en FREEPDB1.
-- Incorpora CLIENTES al módulo Ventas y lo vincula con VENTAS.
-- El backend opera con el usuario técnico PANADERIA_APP,
-- que recibe permisos al final de este script.
-- El script es incremental: NO borra ni modifica datos de VENTAS.

-- ====================================================================
-- 1. PAN_VENTAS.CLIENTES
-- ====================================================================

-- CLIENTES es una entidad maestra no transaccional: identifica a quién se
-- vende y no depende deAdministración ni de Inventario, por lo que puede
-- analizar las ventas que ya existen.
-- NUMERO_DOCUMENTO admite varios NULL porque los clientes de tipo
-- SIN_DOCUMENTO (por ejemplo "Consumidor final") no llevan documento;
-- la unicidad solo aplica cuando el número existe.

CREATE TABLE PAN_VENTAS.CLIENTES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIPO_DOCUMENTO VARCHAR2(20) NOT NULL,
    NUMERO_DOCUMENTO VARCHAR2(20),
    NOMBRE_RAZON_SOCIAL VARCHAR2(150) NOT NULL,
    TELEFONO VARCHAR2(20),
    EMAIL VARCHAR2(120),
    DIRECCION VARCHAR2(200),
    PAIS VARCHAR2(80),
    ACTIVO BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT UK_CLIENTE_DOCUMENTO UNIQUE (NUMERO_DOCUMENTO),
    CONSTRAINT CK_CLIENTE_TIPO_DOCUMENTO CHECK (
        TIPO_DOCUMENTO IN ('DNI', 'RUC', 'CE', 'PASAPORTE', 'SIN_DOCUMENTO')
    ),
    CONSTRAINT CK_CLIENTE_SIN_DOCUMENTO CHECK (
        TIPO_DOCUMENTO <> 'SIN_DOCUMENTO' OR NUMERO_DOCUMENTO IS NULL
    )
);

-- ====================================================================
-- 2. PAN_VENTAS.VENTAS.ID_CLIENTE (inicialmente nullable)
-- ====================================================================
-- Primero se crea la columna para poder asignar un cliente a las ventas
-- existentes. Después de completar los datos se volverá obligatoria.

ALTER TABLE PAN_VENTAS.VENTAS
    ADD (ID_CLIENTE NUMBER);

-- ====================================================================
-- 3. Cliente predeterminado y datos existentes
-- ====================================================================
-- El bloque inserta "Consumidor final" y reutiliza su ID devuelto por
-- RETURNING para asignarlo a todas las ventas que ya existen, de modo que
-- ninguna venta queda huérfana antes de volver obligatorio ID_CLIENTE.

DECLARE
    v_consumidor_final_id PAN_VENTAS.CLIENTES.ID%TYPE;
BEGIN
    INSERT INTO PAN_VENTAS.CLIENTES (
        TIPO_DOCUMENTO, NUMERO_DOCUMENTO, NOMBRE_RAZON_SOCIAL, ACTIVO
    ) VALUES (
        'SIN_DOCUMENTO', NULL, 'Consumidor final', TRUE
    ) RETURNING ID INTO v_consumidor_final_id;

    UPDATE PAN_VENTAS.VENTAS
    SET ID_CLIENTE = v_consumidor_final_id
    WHERE ID_CLIENTE IS NULL;

    DBMS_OUTPUT.PUT_LINE('Cliente "Consumidor final" creado con id ' || v_consumidor_final_id);
END;
/

-- ====================================================================
-- 4. Restricción obligatoria y clave foránea
-- ====================================================================
ALTER TABLE PAN_VENTAS.VENTAS
    MODIFY (ID_CLIENTE NOT NULL);

ALTER TABLE PAN_VENTAS.VENTAS
    ADD CONSTRAINT FK_VENTA_CLIENTE
        FOREIGN KEY (ID_CLIENTE)
        REFERENCES PAN_VENTAS.CLIENTES(ID);

-- ====================================================================
-- 5. Permisos del usuario técnico del backend
-- ====================================================================

GRANT SELECT, INSERT, UPDATE, DELETE
ON PAN_VENTAS.CLIENTES TO PANADERIA_APP;

-- Comprobar el resultado: la columna no admite nulos y toda venta tiene
-- cliente; el conteo de ventas debe coincidir con el total.
SELECT COUNT(*) AS ventas_sin_cliente
FROM PAN_VENTAS.VENTAS
WHERE ID_CLIENTE IS NULL;

SELECT owner, table_name
FROM all_tables
WHERE owner = 'PAN_VENTAS'
ORDER BY table_name;

SELECT ID, TIPO_DOCUMENTO, NUMERO_DOCUMENTO, NOMBRE_RAZON_SOCIAL
FROM PAN_VENTAS.CLIENTES
WHERE NOMBRE_RAZON_SOCIAL = 'Consumidor final';
