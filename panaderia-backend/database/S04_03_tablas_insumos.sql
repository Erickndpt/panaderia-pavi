-- ====================================================================

-- INSUMOS pertenece al módulo Inventario.
-- Almacena las materias primas que la panadería compra y utiliza.
-- Ejemplos: Harina de trigo (KILOGRAMO), Levadura (KILOGRAMO),
-- Azúcar (KILOGRAMO), Bolsas para pan (UNIDAD).

CREATE TABLE PAN_INVENTARIO.INSUMOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(80) NOT NULL,
    UNIDAD_MEDIDA VARCHAR2(20) NOT NULL,
    STOCK_ACTUAL NUMBER(12,3) NOT NULL,
    STOCK_MINIMO NUMBER(12,3) NOT NULL,
    CONSTRAINT UK_INSUMO_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT CK_INSUMO_STOCK_ACTUAL CHECK (STOCK_ACTUAL >= 0),
    CONSTRAINT CK_INSUMO_STOCK_MINIMO CHECK (STOCK_MINIMO >= 0)
);

-- Permisos del usuario técnico del backend.
GRANT SELECT, INSERT, UPDATE, DELETE
ON PAN_INVENTARIO.INSUMOS TO PANADERIA_APP;

-- Comprobar la tabla creada.
SELECT owner, table_name
FROM all_tables
WHERE owner = 'PAN_INVENTARIO'
ORDER BY table_name;