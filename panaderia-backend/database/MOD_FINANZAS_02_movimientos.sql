-- Tabla de movimientos financieros del módulo Finanzas.
-- El backend opera con el usuario técnico PANADERIA_APP,
-- que recibe permisos al final de este script.

-- ====================================================================
-- MÓDULO FINANZAS
-- ====================================================================

-- MOVIMIENTOS_FINANCIEROS pertenece al módulo Finanzas.
-- ORIGEN + ORIGEN_ID referencian por convenio una venta (PAN_VENTAS.VENTAS)
-- o una compra (PAN_COMPRAS.COMPRAS); no llevan FK porque esas tablas
-- viven en otros esquemas y módulos.
-- TIPO distingue INGRESO (de una venta) y EGRESO (de una compra);
-- ESTADO distingue ACTIVO y ANULADO. Anular una venta marca su ingreso
-- como ANULADO, sin eliminarlo, para mantener el histórico.
-- MONTO debe ser mayor o igual a cero; hay UNIQUE(ORIGEN, ORIGEN_ID)
-- para impedir que un mismo origen genere más de un movimiento.

CREATE TABLE PAN_FINANZAS.MOVIMIENTOS_FINANCIEROS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FECHA TIMESTAMP NOT NULL,
    TIPO VARCHAR2(20) NOT NULL,
    ORIGEN VARCHAR2(20) NOT NULL,
    ORIGEN_ID NUMBER NOT NULL,
    CONCEPTO VARCHAR2(150) NOT NULL,
    MONTO NUMBER(12,2) NOT NULL,
    ESTADO VARCHAR2(20) NOT NULL,
    CONSTRAINT UK_MOVIMIENTO_ORIGEN UNIQUE (ORIGEN, ORIGEN_ID),
    CONSTRAINT CK_MOVIMIENTO_TIPO CHECK (TIPO IN ('INGRESO', 'EGRESO')),
    CONSTRAINT CK_MOVIMIENTO_ORIGEN CHECK (ORIGEN IN ('VENTA', 'COMPRA')),
    CONSTRAINT CK_MOVIMIENTO_ESTADO CHECK (ESTADO IN ('ACTIVO', 'ANULADO')),
    CONSTRAINT CK_MOVIMIENTO_MONTO CHECK (MONTO >= 0)
);

-- Permisos del usuario técnico del backend.
GRANT SELECT, INSERT, UPDATE, DELETE
ON PAN_FINANZAS.MOVIMIENTOS_FINANCIEROS TO PANADERIA_APP;

-- Comprobar la tabla creada.
SELECT owner, table_name
FROM all_tables
WHERE owner = 'PAN_FINANZAS'
ORDER BY table_name;