-- Ejecutar como SYSTEM en FREEPDB1.
-- Tablas de producción del módulo Producción.
-- El backend opera con el usuario técnico PANADERIA_APP,
-- que recibe permisos al final de este script.

-- ====================================================================
-- MÓDULO PRODUCCIÓN
-- ====================================================================

-- ORDENES_PRODUCCION pertenece al módulo Producción.
-- ID_PRODUCTO no lleva FK hacia PAN_ADMINISTRACION.PRODUCTOS:
-- la comunicación entre módulos se hará mediante servicios.
-- NOMBRE_PRODUCTO conserva una fotografía histórica del producto.
-- ESTADO distingue el estado de la orden; inicialmente COMPLETADA.

CREATE TABLE PAN_PRODUCCION.ORDENES_PRODUCCION (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PRODUCTO NUMBER NOT NULL,
    NOMBRE_PRODUCTO VARCHAR2(120) NOT NULL,
    FECHA TIMESTAMP NOT NULL,
    ESTADO VARCHAR2(20) NOT NULL,
    CANTIDAD_PRODUCIDA NUMBER(12,3) NOT NULL,
    CONSTRAINT CK_ORDEN_ESTADO CHECK (ESTADO IN ('COMPLETADA')),
    CONSTRAINT CK_ORDEN_CANTIDAD CHECK (CANTIDAD_PRODUCIDA > 0)
);

-- DETALLES_CONSUMO pertenece al módulo Producción.
-- ID_INSUMO no lleva FK hacia PAN_INVENTARIO.INSUMOS: los insumos
-- viven en otro esquema y módulo, por lo que se conserva insumoId y
-- las fotografías NOMBRE_INSUMO y UNIDAD_MEDIDA.

CREATE TABLE PAN_PRODUCCION.DETALLES_CONSUMO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_ORDEN NUMBER NOT NULL,
    ID_INSUMO NUMBER NOT NULL,
    NOMBRE_INSUMO VARCHAR2(80) NOT NULL,
    UNIDAD_MEDIDA VARCHAR2(20) NOT NULL,
    CANTIDAD_CONSUMIDA NUMBER(12,3) NOT NULL,
    CONSTRAINT FK_DETALLE_ORDEN
        FOREIGN KEY (ID_ORDEN)
        REFERENCES PAN_PRODUCCION.ORDENES_PRODUCCION(ID),
    CONSTRAINT CK_DETALLE_CANTIDAD CHECK (CANTIDAD_CONSUMIDA > 0)
);

-- Permisos del usuario técnico del backend.
GRANT SELECT, INSERT, UPDATE, DELETE
ON PAN_PRODUCCION.ORDENES_PRODUCCION TO PANADERIA_APP;

GRANT SELECT, INSERT, UPDATE, DELETE
ON PAN_PRODUCCION.DETALLES_CONSUMO TO PANADERIA_APP;

-- Comprobar las tablas creadas.
SELECT owner, table_name
FROM all_tables
WHERE owner = 'PAN_PRODUCCION'
ORDER BY table_name;