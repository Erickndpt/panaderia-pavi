-- Ejecutar como SYSTEM en FREEPDB1.

CREATE TABLE PAN_ADMINISTRACION.CATEGORIAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(80) NOT NULL,
    DESCRIPCION VARCHAR2(200),
    CONSTRAINT UK_CATEGORIA_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE PAN_ADMINISTRACION.PRODUCTOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CATEGORIA NUMBER NOT NULL,
    NOMBRE VARCHAR2(120) NOT NULL,
    PRECIO NUMBER(10,2) NOT NULL,
    CONSTRAINT FK_PRODUCTO_CATEGORIA
        FOREIGN KEY (ID_CATEGORIA)
        REFERENCES PAN_ADMINISTRACION.CATEGORIAS(ID),
    CONSTRAINT CK_PRODUCTO_PRECIO CHECK (PRECIO >= 0)
);

-- Permisos del usuario técnico del backend.
GRANT SELECT, INSERT, UPDATE, DELETE
ON PAN_ADMINISTRACION.CATEGORIAS TO PANADERIA_APP;

GRANT SELECT, INSERT, UPDATE, DELETE
ON PAN_ADMINISTRACION.PRODUCTOS TO PANADERIA_APP;

-- Comprobar las tablas creadas.
SELECT owner, table_name
FROM all_tables
WHERE owner = 'PAN_ADMINISTRACION'
ORDER BY table_name;