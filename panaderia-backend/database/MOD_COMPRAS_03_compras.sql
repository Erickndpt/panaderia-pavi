-- Ejecutar como SYSTEM en FREEPDB1.
-- Tablas de compras del módulo Compras.
-- El backend opera con el usuario técnico PANADERIA_APP,
-- que recibe permisos al final de este script.

-- ====================================================================
-- MÓDULO COMPRAS
-- ====================================================================

-- COMPRAS pertenece al módulo Compras.
-- ID_PROVEEDOR lleva FK hacia PAN_COMPRAS.PROVEEDORES: ambas tablas
-- viven en el mismo esquema y módulo.
-- ESTADO distingue REGISTRADA (activa) y ANULADA (histórica). Anular una
-- compra descuenta del stock de cada insumo y anula su egreso financiero.

CREATE TABLE PAN_COMPRAS.COMPRAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PROVEEDOR NUMBER NOT NULL,
    FECHA TIMESTAMP NOT NULL,
    ESTADO VARCHAR2(20) NOT NULL,
    TOTAL NUMBER(12,2) NOT NULL,
    CONSTRAINT FK_COMPRA_PROVEEDOR
        FOREIGN KEY (ID_PROVEEDOR)
        REFERENCES PAN_COMPRAS.PROVEEDORES(ID),
    CONSTRAINT CK_COMPRA_TOTAL CHECK (TOTAL >= 0),
    CONSTRAINT CK_COMPRA_ESTADO CHECK (ESTADO IN ('REGISTRADA', 'ANULADA'))
);

-- DETALLE_COMPRAS pertenece al módulo Compras.
-- ID_INSUMO no lleva FK hacia PAN_INVENTARIO.INSUMOS: los insumos
-- viven en otro esquema y módulo, por lo que se conserva insumoId y
-- las fotografías NOMBRE_INSUMO y UNIDAD_MEDIDA.

CREATE TABLE PAN_COMPRAS.DETALLE_COMPRAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_COMPRA NUMBER NOT NULL,
    ID_INSUMO NUMBER NOT NULL,
    NOMBRE_INSUMO VARCHAR2(80) NOT NULL,
    UNIDAD_MEDIDA VARCHAR2(20) NOT NULL,
    CANTIDAD NUMBER(12,3) NOT NULL,
    PRECIO_UNITARIO NUMBER(10,2) NOT NULL,
    SUBTOTAL NUMBER(12,2) NOT NULL,
    CONSTRAINT FK_DETALLE_COMPRA
        FOREIGN KEY (ID_COMPRA)
        REFERENCES PAN_COMPRAS.COMPRAS(ID),
    CONSTRAINT CK_DETALLE_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CK_DETALLE_PRECIO CHECK (PRECIO_UNITARIO >= 0),
    CONSTRAINT CK_DETALLE_SUBTOTAL CHECK (SUBTOTAL >= 0)
);

-- Permisos del usuario técnico del backend.
GRANT SELECT, INSERT, UPDATE, DELETE
ON PAN_COMPRAS.COMPRAS TO PANADERIA_APP;

GRANT SELECT, INSERT, UPDATE, DELETE
ON PAN_COMPRAS.DETALLE_COMPRAS TO PANADERIA_APP;

-- Comprobar las tablas creadas.
SELECT owner, table_name
FROM all_tables
WHERE owner = 'PAN_COMPRAS'
ORDER BY table_name;