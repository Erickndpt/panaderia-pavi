-- Ejecutar como SYSTEM en FREEPDB1.
-- Tabla de pagos de venta del módulo Ventas.
-- El backend opera con el usuario técnico PANADERIA_APP,
-- que recibe permisos al final de este script.
-- El script es incremental: NO borra ni modifica datos de VENTAS.

-- ====================================================================
-- MÓDULO VENTAS
-- ====================================================================

-- PAGOS_VENTAS pertenece al módulo Ventas: registra cómo y cuánto se
-- pagó cada venta. Permite más de un pago por venta (por ejemplo, parte
-- en efectivo y el resto con tarjeta), por lo que la relación con
-- VENTAS es 1:N y no 1:1.
-- ID_VENTA lleva FK hacia PAN_VENTAS.VENTAS: ambas tablas viven en el
-- mismo esquema y módulo.
-- MONTO debe ser mayor que cero: un pago de cero no aporta información
-- y un pago negativo (devolución) se modelaría con un registro propio
-- en ESTADO 'ANULADO', nunca invirtiendo el signo.
-- ESTADO distingue REGISTRADO (vigente) y ANULADO (histórico). Anular un
-- pago no lo elimina, para conservar el histórico, igual que ocurre con
-- VENTAS.ESTADO y COMPRAS.ESTADO.
-- El usuario técnico recibe SELECT, INSERT y UPDATE, pero NO DELETE:
-- el histórico de pagos no se borra, se anula.

CREATE TABLE PAN_VENTAS.PAGOS_VENTAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_VENTA NUMBER NOT NULL,
    FECHA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    METODO_PAGO VARCHAR2(30) NOT NULL,
    MONTO NUMBER(12,2) NOT NULL,
    REFERENCIA VARCHAR2(100),
    ESTADO VARCHAR2(20) DEFAULT 'REGISTRADO' NOT NULL,
    CONSTRAINT FK_PAGO_VENTA_VENTA
        FOREIGN KEY (ID_VENTA)
        REFERENCES PAN_VENTAS.VENTAS(ID),
    CONSTRAINT CK_PAGO_VENTA_METODO CHECK (METODO_PAGO IN (
        'EFECTIVO', 'TARJETA', 'TRANSFERENCIA', 'YAPE', 'PLIN', 'OTRO'
    )),
    CONSTRAINT CK_PAGO_VENTA_MONTO CHECK (MONTO > 0),
    CONSTRAINT CK_PAGO_VENTA_ESTADO CHECK (ESTADO IN ('REGISTRADO', 'ANULADO'))
);

-- Índice normal sobre la clave foránea ID_VENTA: permite listar y
-- totalizar los pagos de una venta sin recorrer toda la tabla.
-- El índice se nombra con el esquema PAN_VENTAS de forma explícita: sin
-- ese prefijo Oracle lo crearía en el esquema del usuario que ejecuta el
-- script (SYSTEM) y no en el de la tabla.
CREATE INDEX PAN_VENTAS.IX_PAGO_VENTA_VENTA
    ON PAN_VENTAS.PAGOS_VENTAS (ID_VENTA);

-- ====================================================================
-- Permisos del usuario técnico del backend
-- ====================================================================

GRANT SELECT, INSERT, UPDATE
ON PAN_VENTAS.PAGOS_VENTAS TO PANADERIA_APP;

-- Comprobar la tabla creada.
SELECT owner, table_name
FROM all_tables
WHERE owner = 'PAN_VENTAS'
ORDER BY table_name;

COMMIT;