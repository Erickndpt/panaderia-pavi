-- Ejecutar conectado como SYSTEM a FREEPDB1.
-- Crear únicamente el esquema de Administración.
-- PANADERIA_APP ya fue creado por Docker.

CREATE USER PAN_ADMINISTRACION
    IDENTIFIED BY "123456"
    DEFAULT TABLESPACE USERS
    TEMPORARY TABLESPACE TEMP
    QUOTA UNLIMITED ON USERS;

GRANT CREATE SESSION, CREATE TABLE,
      CREATE VIEW, CREATE PROCEDURE, CREATE TRIGGER
TO PAN_ADMINISTRACION;

GRANT CREATE SESSION TO PANADERIA_APP;

-- Comprobar los usuarios.
SELECT username, account_status
FROM dba_users
WHERE username IN ('PAN_ADMINISTRACION', 'PANADERIA_APP');