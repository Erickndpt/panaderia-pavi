-- Crear los esquemas de Inventario y Ventas.
-- PANADERIA_APP ya fue creado por Docker; no volver a crearlo.

CREATE USER PAN_INVENTARIO
    IDENTIFIED BY "123456"
    DEFAULT TABLESPACE USERS
    TEMPORARY TABLESPACE TEMP
    QUOTA UNLIMITED ON USERS;

GRANT CREATE SESSION, CREATE TABLE,
      CREATE VIEW, CREATE PROCEDURE, CREATE TRIGGER
TO PAN_INVENTARIO;

CREATE USER PAN_VENTAS
    IDENTIFIED BY "123456"
    DEFAULT TABLESPACE USERS
    TEMPORARY TABLESPACE TEMP
    QUOTA UNLIMITED ON USERS;

GRANT CREATE SESSION, CREATE TABLE,
      CREATE VIEW, CREATE PROCEDURE, CREATE TRIGGER
TO PAN_VENTAS;

-- Comprobar los usuarios.
SELECT username, account_status
FROM dba_users
WHERE username IN ('PAN_INVENTARIO', 'PAN_VENTAS', 'PANADERIA_APP');