-- Panaderia Pavi - creacion segura de copias particionadas para demostracion
-- No modifica, renombra ni elimina las tablas operativas de la aplicacion.
-- Las copias conservan los datos actuales, pero no sustituyen a las tablas reales.

SET SERVEROUTPUT ON
SET PAGESIZE 200
SET LINESIZE 220

PROMPT === CREACION DE COPIAS PARTICIONADAS POR RANGO DE FECHA ===

DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe
    FROM all_tables
    WHERE owner = 'PAN_VENTAS'
      AND table_name = 'VENTAS_PART';

    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE q'~
            CREATE TABLE PAN_VENTAS.VENTAS_PART
            PARTITION BY RANGE (FECHA) (
                PARTITION P_ANTES_2025 VALUES LESS THAN (TIMESTAMP '2025-01-01 00:00:00'),
                PARTITION P_2025       VALUES LESS THAN (TIMESTAMP '2026-01-01 00:00:00'),
                PARTITION P_2026       VALUES LESS THAN (TIMESTAMP '2027-01-01 00:00:00'),
                PARTITION P_FUTURO     VALUES LESS THAN (MAXVALUE)
            )
            AS SELECT * FROM PAN_VENTAS.VENTAS
        ~';
        DBMS_OUTPUT.PUT_LINE('CREADA: PAN_VENTAS.VENTAS_PART');
    ELSE
        DBMS_OUTPUT.PUT_LINE('OMITIDA: PAN_VENTAS.VENTAS_PART ya existe');
    END IF;
END;
/

