-- Script de comprobacion: no modifica las tablas operativas.

SET PAGESIZE 200
SET LINESIZE 220

PROMPT === 1. ESTADO DE TABLAS ORIGINALES Y COPIAS PARTICIONADAS ===
SELECT owner,
       table_name,
       partitioned
FROM all_tables
WHERE (owner = 'PAN_VENTAS' AND table_name IN ('VENTAS', 'VENTAS_PART'))
   OR (owner = 'PAN_COMPRAS' AND table_name IN ('COMPRAS', 'COMPRAS_PART'))
   OR (owner = 'PAN_PRODUCCION' AND table_name IN ('ORDENES_PRODUCCION', 'ORDENES_PRODUCCION_PART'))
   OR (owner = 'PAN_FINANZAS' AND table_name IN ('MOVIMIENTOS_FINANCIEROS', 'MOVIMIENTOS_FINANCIEROS_PART'))
ORDER BY owner, table_name;

PROMPT === 2. PARTICIONES CREADAS Y LIMITES ===
SELECT table_owner,
       table_name,
       partition_name,
       partition_position,
       high_value
FROM all_tab_partitions
WHERE (table_owner = 'PAN_VENTAS' AND table_name = 'VENTAS_PART')
   OR (table_owner = 'PAN_COMPRAS' AND table_name = 'COMPRAS_PART')
   OR (table_owner = 'PAN_PRODUCCION' AND table_name = 'ORDENES_PRODUCCION_PART')
   OR (table_owner = 'PAN_FINANZAS' AND table_name = 'MOVIMIENTOS_FINANCIEROS_PART')
ORDER BY table_owner, table_name, partition_position;

PROMPT === 3. COMPARACION DE FILAS: ORIGINAL FRENTE A COPIA ===
SELECT 'VENTAS' AS MODULO,
       (SELECT COUNT(*) FROM PAN_VENTAS.VENTAS) AS ORIGINAL,
       (SELECT COUNT(*) FROM PAN_VENTAS.VENTAS_PART) AS COPIA_PARTICIONADA
FROM dual
UNION ALL
SELECT 'COMPRAS',
       (SELECT COUNT(*) FROM PAN_COMPRAS.COMPRAS),
       (SELECT COUNT(*) FROM PAN_COMPRAS.COMPRAS_PART)
FROM dual
UNION ALL
SELECT 'PRODUCCION',
       (SELECT COUNT(*) FROM PAN_PRODUCCION.ORDENES_PRODUCCION),
       (SELECT COUNT(*) FROM PAN_PRODUCCION.ORDENES_PRODUCCION_PART)
FROM dual
UNION ALL
SELECT 'FINANZAS',
       (SELECT COUNT(*) FROM PAN_FINANZAS.MOVIMIENTOS_FINANCIEROS),
       (SELECT COUNT(*) FROM PAN_FINANZAS.MOVIMIENTOS_FINANCIEROS_PART)
FROM dual;

PROMPT === 4. DISTRIBUCION DE VENTAS POR PARTICION ===
SELECT 'P_ANTES_2025' AS PARTICION, COUNT(*) AS FILAS
FROM PAN_VENTAS.VENTAS_PART PARTITION (P_ANTES_2025)
UNION ALL
SELECT 'P_2025', COUNT(*)
FROM PAN_VENTAS.VENTAS_PART PARTITION (P_2025)
UNION ALL
SELECT 'P_2026', COUNT(*)
FROM PAN_VENTAS.VENTAS_PART PARTITION (P_2026)
UNION ALL
SELECT 'P_FUTURO', COUNT(*)
FROM PAN_VENTAS.VENTAS_PART PARTITION (P_FUTURO);

PROMPT === 5. PLAN DE EJECUCION: PODA DE PARTICIONES EN VENTAS 2026 ===
EXPLAIN PLAN SET STATEMENT_ID = 'PAVI_VENTAS_2026' FOR
SELECT *
FROM PAN_VENTAS.VENTAS_PART
WHERE FECHA >= TIMESTAMP '2026-01-01 00:00:00'
  AND FECHA <  TIMESTAMP '2027-01-01 00:00:00';

SELECT *
FROM TABLE(DBMS_XPLAN.DISPLAY(NULL, 'PAVI_VENTAS_2026', 'BASIC +PARTITION'));

