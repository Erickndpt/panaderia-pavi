-- Tabla de proveedores del módulo Compras.
-- El backend opera con el usuario técnico PANADERIA_APP,
-- que recibe permisos al final de este script.

-- ====================================================================
-- MÓDULO COMPRAS
-- ====================================================================

-- PROVEEDORES pertenece al módulo Compras.
-- ACTIVO usa el tipo BOOLEAN nativo de Oracle 23, compatible con la
-- propiedad Boolean de la entidad Java.

CREATE TABLE PAN_COMPRAS.PROVEEDORES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUC VARCHAR2(11) NOT NULL,
    RAZON_SOCIAL VARCHAR2(120) NOT NULL,
    TELEFONO VARCHAR2(20),
    EMAIL VARCHAR2(120),
    ACTIVO BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT UK_PROVEEDOR_RUC UNIQUE (RUC)
);

-- Permisos del usuario técnico del backend.
GRANT SELECT, INSERT, UPDATE, DELETE
ON PAN_COMPRAS.PROVEEDORES TO PANADERIA_APP;

-- Comprobar la tabla creada.
SELECT owner, table_name
FROM all_tables
WHERE owner = 'PAN_COMPRAS'
ORDER BY table_name;