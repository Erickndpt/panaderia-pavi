GRANT SELECT, INSERT, UPDATE, DELETE
ON PAN_VENTAS.CLIENTES TO PANADERIA_APP;

GRANT SELECT, INSERT, UPDATE, DELETE
ON PAN_VENTAS.VENTAS TO PANADERIA_APP;

GRANT SELECT, INSERT, UPDATE, DELETE
ON PAN_VENTAS.DETALLE_VENTAS TO PANADERIA_APP;

-- Comprobar las tablas creadas.
SELECT owner, table_name
FROM all_tables
WHERE owner IN ('PAN_INVENTARIO', 'PAN_VENTAS')
ORDER BY owner, table_name;