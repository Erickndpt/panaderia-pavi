-- Ejecutar como SYSTEM en FREEPDB1.
-- Tablas de los módulos Inventario y Ventas.
-- El backend opera con el usuario técnico PANADERIA_APP,
-- que recibe permisos al final de este script.

-- ====================================================================
-- MÓDULO INVENTARIO
-- ====================================================================

-- EXISTENCIAS pertenece al módulo Inventario.
-- Almacena la cantidad disponible de un producto.
-- ID_PRODUCTO no lleva FK hacia PAN_ADMINISTRACION.PRODUCTOS:
-- la comunicación entre módulos se hará mediante servicios.

CREATE TABLE PAN_INVENTARIO.EXISTENCIAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PRODUCTO NUMBER NOT NULL,
    CANTIDAD NUMBER(12,3) NOT NULL,
    CONSTRAINT UK_EXISTENCIA_PRODUCTO UNIQUE (ID_PRODUCTO),
    CONSTRAINT CK_EXISTENCIA_CANTIDAD CHECK (CANTIDAD >= 0)
);

-- ====================================================================
-- MÓDULO VENTAS
-- ====================================================================

-- CLIENTES pertenece al módulo Ventas: es una entidad maestra no
-- transaccional que identifica a quién se vende.
-- Se crea antes que VENTAS porque VENTAS.ID_CLIENTE la referencia.
-- NUMERO_DOCUMENTO admite varios NULL porque los clientes de tipo
-- SIN_DOCUMENTO no llevan documento; la unicidad solo aplica cuando
-- el número existe.

CREATE TABLE PAN_VENTAS.CLIENTES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIPO_DOCUMENTO VARCHAR2(20) NOT NULL,
    NUMERO_DOCUMENTO VARCHAR2(20),
    NOMBRE_RAZON_SOCIAL VARCHAR2(150) NOT NULL,
    TELEFONO VARCHAR2(20),
    EMAIL VARCHAR2(120),
    DIRECCION VARCHAR2(200),
    PAIS VARCHAR2(80),
    ACTIVO BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT UK_CLIENTE_DOCUMENTO UNIQUE (NUMERO_DOCUMENTO),
    CONSTRAINT CK_CLIENTE_TIPO_DOCUMENTO CHECK (
        TIPO_DOCUMENTO IN ('DNI', 'RUC', 'CE', 'PASAPORTE', 'SIN_DOCUMENTO')
    ),
    CONSTRAINT CK_CLIENTE_SIN_DOCUMENTO CHECK (
        TIPO_DOCUMENTO <> 'SIN_DOCUMENTO' OR NUMERO_DOCUMENTO IS NULL
    )
);

-- Cliente predeterminado para las ventas rápidas de mostrador.

INSERT INTO PAN_VENTAS.CLIENTES (
    TIPO_DOCUMENTO, NUMERO_DOCUMENTO, NOMBRE_RAZON_SOCIAL, ACTIVO
) VALUES (
    'SIN_DOCUMENTO', NULL, 'Consumidor final', TRUE
);

-- VENTAS pertenece al módulo Ventas.
-- TIPO distingue venta local y exportación: EXPORTACION es un tipo
-- de Venta, no otro módulo.
-- PAIS_DESTINO solo aplica a las exportaciones y no sustituye al cliente:
-- toda venta, local o de exportación, pertenece a un cliente.
-- ID_CLIENTE lleva FK hacia PAN_VENTAS.CLIENTES: ambas tablas viven en
-- el mismo esquema y módulo.
-- VENDEDOR_ID guarda el claim sub del JWT de Keycloak del usuario que
-- registró la venta. Es VARCHAR2(36) porque el sub es un UUID. Permite
-- NULL para conservar las ventas históricas anteriores a la autenticación.

CREATE TABLE PAN_VENTAS.VENTAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CLIENTE NUMBER NOT NULL,
    FECHA TIMESTAMP NOT NULL,
    TIPO VARCHAR2(20) NOT NULL,
    PAIS_DESTINO VARCHAR2(80),
    ESTADO VARCHAR2(20) NOT NULL,
    VENDEDOR_ID VARCHAR2(36),
    VENDEDOR_USERNAME VARCHAR2(100),
    VENDEDOR_NOMBRE VARCHAR2(200),
    TOTAL NUMBER(12,2) NOT NULL,
    CONSTRAINT FK_VENTA_CLIENTE
        FOREIGN KEY (ID_CLIENTE)
        REFERENCES PAN_VENTAS.CLIENTES(ID),
    CONSTRAINT CK_VENTA_TOTAL CHECK (TOTAL >= 0),
    CONSTRAINT CK_VENTA_TIPO CHECK (TIPO IN ('LOCAL', 'EXPORTACION')),
    CONSTRAINT CK_VENTA_PAIS_TIPO CHECK (
        (TIPO = 'LOCAL' AND PAIS_DESTINO IS NULL)
        OR (TIPO = 'EXPORTACION' AND PAIS_DESTINO IS NOT NULL)
    )
);

-- DETALLE_VENTAS pertenece al módulo Ventas (no es otro módulo):
-- los ítems conservan una copia histórica del producto vendido.
-- ID_PRODUCTO no lleva FK hacia Administración por el mismo
-- principio de límites entre esquemas.

CREATE TABLE PAN_VENTAS.DETALLE_VENTAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_VENTA NUMBER NOT NULL,
    ID_PRODUCTO NUMBER NOT NULL,
    NOMBRE_PRODUCTO VARCHAR2(120) NOT NULL,
    PRECIO_UNITARIO NUMBER(10,2) NOT NULL,
    CANTIDAD NUMBER(10) NOT NULL,
    SUBTOTAL NUMBER(12,2) NOT NULL,
    CONSTRAINT FK_DETALLE_VENTA
        FOREIGN KEY (ID_VENTA)
        REFERENCES PAN_VENTAS.VENTAS(ID),
    CONSTRAINT CK_DETALLE_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CK_DETALLE_PRECIO CHECK (PRECIO_UNITARIO >= 0),
    CONSTRAINT CK_DETALLE_SUBTOTAL CHECK (SUBTOTAL >= 0)
);

-- Permisos del usuario técnico del backend.
GRANT SELECT, INSERT, UPDATE, DELETE
